"""Command line: python -m sayless <command> [--format landscape|portrait|both]

  inventory     list the supplied garments and their mattes
  mattes        write a check sheet of the eight cutouts on charcoal
  storyboard    nine storyboard frames + a captioned sheet
  audio         synthesise music and sound design, master, write stems
  animatic      low-resolution film with timecode, bar grid and VO captions
  preview       full-resolution film with a small review slate
  contact       contact sheet (one frame every 0.4 s)
  transitions   every other frame around each of the nine handoffs
  qc            automated checks over all 1,440 frames
  final         clean masters - refused until the preview is approved
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

from . import assets, export, film, matte, qc, render, review
from .audio import mix
from .config import FORMATS, FPS, GARMENT_LABEL, N_FRAMES, ROOT

OUT = ROOT / "out"
REVIEW = ROOT / "review"


def _formats(arg: str) -> list[str]:
    return list(FORMATS) if arg == "both" else [arg]


def _save(im, path: Path, quality: int = 90) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(im, np.ndarray):
        im = Image.fromarray(im)
    im.save(path, quality=quality) if path.suffix.lower() in (".jpg", ".jpeg") else im.save(path)
    print("wrote", path.relative_to(ROOT))


def cmd_inventory(a):
    man = matte.load_manifest()
    for slot, label in GARMENT_LABEL.items():
        key = assets.SLOT_FILE_KEY.get(slot, slot)
        rgba, info = matte.cutout(key)
        print(f"{slot:13s} {label:34s} {man[key]['original']:14s} source {info['source_size'][0]}x{info['source_size'][1]}"
              f"  cutout {rgba.shape[1]}x{rgba.shape[0]}  coverage {info['coverage']:.2f}")
    print("hero matches the brief's track jacket:", assets.hero_is_brief_item())
    print("O mark:", assets.o_mark_status())


def cmd_mattes(a):
    tiles = []
    for slot in GARMENT_LABEL:
        rgba, _ = matte.cutout(assets.SLOT_FILE_KEY.get(slot, slot))
        al = rgba[..., 3:4].astype(np.float32) / 255
        comp = (rgba[..., :3] * al + np.float32([0x17, 0x16, 0x15]) * 1.5 * (1 - al)).astype(np.uint8)
        s = 560 / max(comp.shape[:2])
        t = cv2.resize(comp, None, fx=s, fy=s, interpolation=cv2.INTER_AREA)
        c = np.full((580, 580, 3), (35, 33, 32), np.uint8)
        y, x = (580 - t.shape[0]) // 2, (580 - t.shape[1]) // 2
        c[y:y + t.shape[0], x:x + t.shape[1]] = t
        tiles.append(c)
    _save(np.vstack([np.hstack(tiles[:4]), np.hstack(tiles[4:])]), REVIEW / "mattes.jpg", 92)


def cmd_storyboard(a):
    for name in _formats(a.format):
        fmt = FORMATS[name]
        scale = 0.5 if name == "landscape" else 0.45
        frames = [export.still(name, t, scale) for t in review.STORYBOARD_TIMES]
        for k, fr in enumerate(frames):
            _save(fr, REVIEW / "storyboard" / f"{name}_{k + 1:02d}.jpg", 92)
        sheet_frames = frames if name == "landscape" else [
            cv2.resize(f, None, fx=0.8, fy=0.8, interpolation=cv2.INTER_AREA) for f in frames]
        _save(review.storyboard_sheet(sheet_frames, fmt, f"Storyboard · {fmt.width} x {fmt.height} · nine scenes"),
              REVIEW / f"storyboard_{name}.jpg", 90)


def cmd_audio(a):
    rep = mix.build(OUT / "audio")
    print(json.dumps(rep, indent=2))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "cue_sheet.md").write_text(
        "# Sound design cue sheet\n\nEvery cue accompanies motion that is visible on screen. "
        "Levels are peak, before mastering. Generated by `python -m sayless audio`.\n\n" + mix.cue_sheet_md() + "\n")
    print("wrote docs/cue_sheet.md")


def _film(a, mode: str, scale: float, crf: int, preset: str, dest: Path):
    audio = OUT / "audio" / "master.wav"
    if not audio.exists():
        mix.build(OUT / "audio")
    for name in _formats(a.format):
        silent = OUT / "_tmp" / f"{mode}_{name}.mp4"
        export.encode(name, silent, scale=scale, mode=mode, crf=crf, preset=preset)
        out = dest / f"{mode}_{name}.mp4"
        out.parent.mkdir(parents=True, exist_ok=True)
        export.mux(silent, audio, out)
        silent.unlink()
        print("wrote", out.relative_to(ROOT))
        print("  ", export.probe(out).replace("\n", "\n   "))


def cmd_animatic(a):
    _film(a, "animatic", 0.5, 21, "medium", REVIEW)


def cmd_preview(a):
    _film(a, "preview", 1.0, 17, "medium", OUT)


def cmd_contact(a):
    for name in _formats(a.format):
        scale = 0.2 if name == "landscape" else 0.16
        idx = list(range(0, N_FRAMES, 24))
        frames = [render.render_frame(film.build(name), i, scale=scale) for i in idx]
        labels = [f"{i / FPS:05.2f}s  f{i:04d}" for i in idx]
        cols = 10 if name == "landscape" else 15
        _save(review.contact_sheet(frames, labels, cols, f"SAY LESS. · contact sheet · {name} · one frame every 0.4 s"),
              REVIEW / f"contact_{name}.jpg", 88)


def cmd_transitions(a):
    for name in _formats(a.format):
        scale = 0.2 if name == "landscape" else 0.16
        L = film.build(name)
        for k, (tb, label) in enumerate(review.TRANSITIONS, 1):
            f0 = int(round(tb * FPS))
            idx = [i for i in range(f0 - 30, f0 + 30, 2) if 0 <= i < N_FRAMES]
            frames = [render.render_frame(L, i, scale=scale) for i in idx]
            labels = [f"f{i:04d}  {i / FPS:05.2f}s" for i in idx]
            cols = 10 if name == "landscape" else 15
            _save(review.contact_sheet(frames, labels, cols, f"Handoff {label} · {name} · every 2nd frame, {idx[0]}-{idx[-1]}"),
                  REVIEW / "transitions" / f"{name}_{k:02d}.jpg", 86)


def cmd_qc(a):
    ok = True
    for name in _formats(a.format):
        rep = qc.run(name)
        p = REVIEW / f"qc_{name}.json"
        p.parent.mkdir(exist_ok=True)
        p.write_text(qc.to_json(rep))
        print("wrote", p.relative_to(ROOT), "PASSED" if rep["passed"] else "NEEDS ATTENTION")
        ok &= rep["passed"]
    sys.exit(0 if ok else 1)


def cmd_final(a):
    problems = []
    if not a.approved:
        problems.append("the preview has not been approved (pass --approved once it is)")
    if not assets.hero_is_brief_item():
        problems.append("the hero slot holds a stand-in; set \"matches_brief\": true in the manifest once the hero is confirmed")
    if assets.o_mark_status() != "approved":
        problems.append("no approved O mark at assets/brand/o_mark.png (the extraction is a proposal)")
    if problems and not a.force:
        print("Final export refused:\n  - " + "\n  - ".join(problems))
        sys.exit(2)
    for name in _formats(a.format):
        silent = OUT / "_tmp" / f"final_{name}.mp4"
        export.encode(name, silent, scale=1.0, mode="clean", crf=14, preset="slow")
        mix.build(OUT / "audio")
        export.mux(silent, OUT / "audio" / "master.wav", OUT / "final" / f"say_less_{name}.mp4")
        export.mux(silent, OUT / "audio" / "master_no_voice.wav", OUT / "final" / f"say_less_{name}_no_voice.mp4")
        silent.unlink()


def main():
    ap = argparse.ArgumentParser(prog="sayless", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["inventory", "mattes", "storyboard", "audio", "animatic", "preview", "contact",
                                        "transitions", "qc", "final"])
    ap.add_argument("--format", default="both", choices=["landscape", "portrait", "both"])
    ap.add_argument("--approved", action="store_true", help="final: the preview was approved by the owner")
    ap.add_argument("--force", action="store_true", help="final: export even with stand-ins (not for release)")
    a = ap.parse_args()
    globals()[f"cmd_{a.command}"](a)


if __name__ == "__main__":
    main()
